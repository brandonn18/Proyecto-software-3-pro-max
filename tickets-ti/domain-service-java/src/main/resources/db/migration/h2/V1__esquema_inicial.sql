-- M-04. Esquema inicial para H2 (desarrollo y pruebas), equivalente a ../mysql/V1__esquema_inicial.sql.
-- Difiere en los tipos: Hibernate guarda los Instant como `timestamp(6) with time zone` en H2 y como `datetime(6)` en MySQL,
-- y `ddl-auto: validate` exige el tipo exacto de cada base. Toda migración nueva va en las dos carpetas, con el mismo número.

create table tecnico (
    id bigint generated by default as identity,
    version bigint,
    username varchar(60) not null,
    primary key (id),
    constraint uk_tecnico_username unique (username)
);

create table tecnico_categoria (
    tecnico_id bigint not null,
    categoria varchar(40) not null,
    primary key (tecnico_id, categoria)
);

create table ticket (
    anio integer not null,
    reaperturas integer not null,
    consecutivo bigint not null,
    creado_en timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    vence_sla timestamp(6) with time zone not null,
    version bigint,
    prioridad varchar(10) not null,
    estado varchar(12) not null,
    tipo varchar(12) not null,
    codigo varchar(20) not null,
    categoria varchar(40) not null,
    creado_por varchar(60) not null,
    tecnico varchar(60),
    titulo varchar(120) not null,
    descripcion varchar(2000) not null,
    primary key (id),
    constraint uk_ticket_codigo unique (codigo),
    constraint uk_ticket_anio_consecutivo unique (anio, consecutivo)
);

create table ticket_historial (
    orden integer not null,
    cuando timestamp(6) with time zone not null,
    ticket_id bigint not null,
    estado_a varchar(12) not null,
    estado_de varchar(12),
    por varchar(60) not null,
    detalle varchar(600) not null,
    primary key (orden, ticket_id)
);

create index ix_ticket_tecnico_categoria
    on ticket (tecnico, categoria, estado);

create index ix_ticket_creado_por
    on ticket (creado_por);

